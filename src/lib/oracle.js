import oracledb from 'oracledb';

let clientInitialized = false;

export function getOracleConfig() {
  const user = process.env.DB_USER;
  const password = process.env.DB_PASSWORD;
  const connectString = process.env.DB_CONNECT_STRING;

  if (!user || !password || !connectString) {
    throw new Error('Oracle environment variables are not configured. Set DB_USER, DB_PASSWORD, and DB_CONNECT_STRING.');
  }

  return { user, password, connectString };
}

export async function initOracleClient() {
  if (clientInitialized) return;

  if (process.env.ORACLE_LIB_DIR) {
    oracledb.initOracleClient({ libDir: process.env.ORACLE_LIB_DIR });
  }

  clientInitialized = true;
}

export async function getOracleConnection() {
  await initOracleClient();
  const config = getOracleConfig();

  return oracledb.getConnection(config);
}

export async function ensureTrackerTable(connection) {
  await connection.execute(`
    BEGIN
      EXECUTE IMMEDIATE '
        CREATE TABLE tracker_records (
          id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          name VARCHAR2(200) NOT NULL,
          status VARCHAR2(50) NOT NULL,
          notes VARCHAR2(500),
          created_at TIMESTAMP DEFAULT SYSTIMESTAMP
        )
      ';
    EXCEPTION
      WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
          RAISE;
        END IF;
    END;
  `);
}
